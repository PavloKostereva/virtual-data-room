function buildPdf(title: string, targetBytes: number): Buffer {
  const body = `BT /F1 18 Tf 40 140 Td (${title.replace(/[()\\]/g, "")}) Tj ET
BT /F1 10 Tf 40 110 Td (Sample document generated by the Vault seed script.) Tj ET`;

  const build = (padding: string) => `%PDF-1.4
1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj
2 0 obj<</Type/Pages/Kids[3 0 R]/Count 1>>endobj
3 0 obj<</Type/Page/Parent 2 0 R/MediaBox[0 0 595 200]/Resources<</Font<</F1 5 0 R>>>>/Contents 4 0 R>>endobj
4 0 obj<</Length ${body.length}>>stream
${body}
endstream endobj
5 0 obj<</Type/Font/Subtype/Type1/BaseFont/Helvetica>>endobj
${padding}trailer<</Root 1 0 R/Size 6>>
%%EOF`;

  const base = build("");
  const shortfall = targetBytes - Buffer.byteLength(base, "utf8");
  const padding = shortfall > 2 ? `%${"0".repeat(shortfall - 2)}\n` : "";

  return Buffer.from(build(padding), "utf8");
}

async function writeSeedObject(storageKey: string, contents: Buffer): Promise<void> {
  if (STORAGE_DRIVER !== "local") return;
  const target = path.join(STORAGE_DIR, storageKey);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, contents);
}

